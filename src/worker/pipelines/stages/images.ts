function slugFor(ctx: PipelineContext): string {
  return ctx.task.slug || slugify(ctx.task.keyword) || 'image';
}

// ---------------- Tigram: planned and generated by ChatGPT ----------------

type TigramImagesData = { plan?: PlannedImage[]; done?: Record<string, { path: string; alt: string }> };

export function tigramImagesStage(progress = 62): PipelineStage {
  return {
    key: 'IMAGES',
    label: 'Images',
    kind: 'chatgpt',
    status: 'OPTIMIZING',
    progress,
    async run(ctx): Promise<StageOutcome> {
      if (!ctx.imagesEnabled()) return { outcome: 'completed', skipped: true, message: 'Images are off for this website' };
      const prev = (await ctx.stageData<TigramImagesData>('IMAGES')) ?? {};
      const resume = ctx.mode === 'run' || ctx.attempt > 1;
      let plan = resume ? prev.plan : undefined;
      const done: Record<string, { path: string; alt: string }> = resume ? { ...(prev.done ?? {}) } : {};
      if (!plan?.length) {
        const a = await ctx.askChatGPT('IMAGES', 'image_plan', {}, { label: 'Image plan' });
        plan = parseImagePlan(a.markdown);
        if (!plan.length) throw new Error('The image plan could not be read (expected IMAGE 1: … lines).');
        await ctx.saveProgress({ plan, done });
      }
      const website = ctx.task.website;
      const logo = await loadLogo(website);
      const accent = await accentColour(website, logo);
      const slug = slugFor(ctx);
      for (let i = 0; i < plan.length; i++) {
        if (done[i]) continue;
        const item = plan[i]!;
        const a = await ctx.askChatGPT('IMAGES', 'image', { image_description: item.description, image_text: item.text ?? '' }, { images: true, imageCount: 1, label: `Image ${i + 1}` });
        const file = a.imageFiles[0];
        if (!file) throw new Error(`ChatGPT did not return picture ${i + 1}.`);
        const buf = await readData(file.path);
        const meta = await sharp(buf).metadata();
        const design = designFor(i === 0 ? 'featured' : 'body', website ?? { accentColour: null, logoPosition: 'bottom-right', featuredStyle: 'single', imageTemplate: null }, accent, 1);
        const png = await renderDesign(design, { pictures: [{ buffer: buf, width: meta.width ?? 1920, height: meta.height ?? 1080 }], logo, vars: { title: ctx.task.selectedTitle ?? '', keyword: ctx.task.keyword, image_text: item.text ?? '' } });
        const out = taskMedia(ctx.task.id, i === 0 ? `${slug}.jpg` : `${slug}-${i}.jpg`);
        await fs.writeFile(out.abs, await toJpegOut(png, 90));
        done[i] = { path: out.rel, alt: item.alt.slice(0, 125) };
        await ctx.saveProgress({ plan, done });
      }
      const data: ImagesData & TigramImagesData = {
        featured: done[0] ?? null,
        body: plan.slice(1).map((_, k) => done[k + 1]).filter(Boolean).map((d, k) => ({ key: `body-${k + 1}`, path: d!.path, alt: d!.alt })),
        plan,
        done,
      };
      return { outcome: 'completed', data, message: `${Object.keys(done).length} picture(s) created` };
    },
  };
}

// ---------------- Celebrity: image search gallery ----------------

type CelebImagesData = ImagesData & { pictures?: GalleryPicture[]; photoChecked?: boolean; notes?: string[] };

async function collectGallery(ctx: PipelineContext): Promise<GalleryPicture[]> {
  let answer;
  try {
    answer = await ctx.askChatGPT('IMAGES', 'image_search', {}, { gallery: true, label: 'Image search' });
  } catch (err) {
    if (!(err instanceof NoImagesError)) throw err;
    await ctx.log.warn('ChatGPT answered the image search without a gallery; trying once more in a new chat.');
    try {
      answer = await ctx.askChatGPT('IMAGES', 'image_search', {}, { gallery: true, newChat: true, fresh: true, label: 'Image search (new chat)' });
    } catch (err2) {
      if (err2 instanceof NoImagesError) throw new Error('ChatGPT answered the image search with text only, twice. No pictures could be collected.');
      throw err2;
    }
  }
  const buffers: { buf: Buffer; source: string; rel?: string }[] = [];
  for (const f of answer.imageFiles) buffers.push({ buf: await readData(f.path), source: f.source ?? 'gallery', rel: f.path });
  let n = 0;
  for (const link of answer.imageLinks.slice(0, 12)) {
    try {
      const res = await safeFetch(link.url, { maxBytes: 12 * 1024 * 1024, accept: 'image/*', timeoutMs: 20_000 });
      if (res.status !== 200 || !/^image\//.test(res.contentType)) throw new Error(`HTTP ${res.status} ${res.contentType}`);
      const jpg = await toJpeg(res.body, 3000, 92);
      const out = taskMedia(ctx.task.id, `src-link-${++n}.jpg`);
      await fs.writeFile(out.abs, jpg);
      buffers.push({ buf: jpg, source: link.url, rel: out.rel });
    } catch (err) {
      await ctx.log.info(`Picture link skipped (${link.url}): ${err instanceof Error ? err.message : err}`);
    }
  }
  const pics: GalleryPicture[] = [];
  for (let i = 0; i < buffers.length; i++) {
    try {
      const b = buffers[i]!;
      const facts = await imageFacts(b.buf);
      if (Math.min(facts.width, facts.height) < 250) continue;
      pics.push({ id: `p${i + 1}`, path: b.rel!, ...facts, faces: null, faceFp: null, source: b.source });
    } catch {
      // not a picture
    }
  }
  if (!pics.length) throw new Error('The image search gave no usable pictures.');

  if (faceToolAvailable()) {
    try {
      const faces = await detectFaces(await Promise.all(pics.map((p) => readData(p.path))));
      if (faces) {
        for (let i = 0; i < pics.length; i++) {
          const p = pics[i]!;
          p.faces = faces[i] ?? [];
          p.faceFp = p.faces.length ? await faceFingerprint(await readData(p.path), p.faces, p.width, p.height) : null;
        }
      }
    } catch (err) {
      await ctx.log.warn(`Face detection failed; pictures are ordered without it (${err instanceof Error ? err.message : err}).`);
    }
  } else {
    await ctx.log.warn('Face detector not installed (npm run tools:install); pictures are ordered by size and sharpness.');
  }
  dedupePictures(pics);
  markSoft(pics);
  const dropped = pics.filter((p) => p.dropped);
  if (dropped.length) await ctx.log.info(`${dropped.length} duplicate picture(s) removed.`, dropped.map((d) => `${d.id}: ${d.dropped}`));
  return orderPictures(pics);
}

async function photoCheck(ctx: PipelineContext, ordered: GalleryPicture[]): Promise<GalleryPicture[]> {
  const chosen = ordered.slice(0, 8);
  const attachments = [];
  for (let i = 0; i < chosen.length; i++) {
    const out = taskMedia(ctx.task.id, `check-${i + 1}.jpg`);
    await fs.writeFile(out.abs, await toJpeg(await readData(chosen[i]!.path), 1024, 85));
    attachments.push({ name: `photo-${i + 1}.jpg`, mime: 'image/jpeg', path: out.rel });
  }
  const a = await ctx.askChatGPT('IMAGES', 'photo_check', { photo_count: chosen.length }, { attachments, label: 'Photo check' });
  const verdicts = parsePhotoCheck(a.markdown, chosen.length);
  if (!verdicts.size) throw new Error('the answer had no "N: watermark=… | collage=… | alt=…" lines');
  chosen.forEach((p, i) => {
    const v = verdicts.get(i + 1);
    if (!v) return;
    p.watermark = v.watermark;
    p.collage = v.collage;
    p.alt = v.alt;
  });
  await ctx.log.info(`Photo check: ${chosen.filter((p) => p.watermark).length} watermarked, ${chosen.filter((p) => p.collage).length} collage(s).`);
  return [...orderAfterCheck(chosen), ...ordered.slice(8)];
}

async function preparePicture(ctx: PipelineContext, p: GalleryPicture, slot: { w: number; h: number }, notes: string[]): Promise<RenderPicture> {
  let buffer = await readData(p.path);
  let width = p.width;
  let height = p.height;
  let faces = p.faces ?? undefined;
  const stretch = Math.max(slot.w / width, slot.h / height);
  if (ctx.settings.enhanceCelebrityImages && (stretch > 2 || p.soft)) {
    if (upscalerAvailable()) {
      const up = await upscale(buffer);
      if (up) {
        const meta = await sharp(up).metadata();
        const f = (meta.width ?? width) / width;
        buffer = up;
        width = meta.width ?? width;
        height = meta.height ?? height;
        faces = faces?.map((b) => ({ x: b.x * f, y: b.y * f, w: b.w * f, h: b.h * f }));
        notes.push(`${p.id} enhanced (${stretch > 2 ? `stretched ${stretch.toFixed(1)}×` : 'soft'})`);
      }
    } else if (!notes.includes('upscayl-missing')) {
      notes.push('upscayl-missing');
      await ctx.log.warn('Upscayl is not installed; soft or small pictures are used as they are.');
    }
  }
  return { buffer, width, height, faces };
}

export function celebrityImagesStage(progress = 68): PipelineStage {
  return {
    key: 'IMAGES',
    label: 'Images',
    kind: 'chatgpt',
    status: 'OPTIMIZING',
    progress,
    async run(ctx): Promise<StageOutcome> {
      if (!ctx.imagesEnabled()) return { outcome: 'completed', skipped: true, message: 'Images are off for this website' };
      const website = ctx.task.website!;
      const resume = ctx.mode === 'run' || ctx.attempt > 1;
      const prev: Partial<CelebImagesData> = resume ? ((await ctx.stageData<CelebImagesData>('IMAGES')) ?? {}) : {};
      const notes: string[] = [];
      const reasons: string[] = [];

      let ordered = prev.pictures;
      if (!ordered?.length) {
        ordered = await collectGallery(ctx);
        await ctx.saveProgress({ pictures: ordered, photoChecked: false });
      }
      let checked = !!prev.photoChecked;
      if (!checked && ctx.settings.celebrityPhotoReview) {
        try {
          ordered = await photoCheck(ctx, ordered);
        } catch (err) {
          await ctx.log.warn(`Photo check skipped: ${err instanceof Error ? err.message : err}`);
          if ((err as { name?: string }).name === 'LoginRequiredError' || (err as { name?: string }).name === 'TaskCancelledError') throw err;
        }
        checked = true;
        await ctx.saveProgress({ pictures: ordered, photoChecked: true });
      }

      const logo = await loadLogo(website);
      const accent = await accentColour(website, logo);
      const featuredDesign = designFor('featured', website, accent, Math.max(1, ordered.length));
      const featuredSlots = Object.keys(slotSizes(featuredDesign)).length || 1;
      const assignment = assignPictures(ordered, featuredSlots, 2);
      if (!assignment.featured.length) {
        return { outcome: 'completed', data: { featured: null, body: [], pictures: ordered }, reviewReasons: ['No usable picture for the featured image.'], message: 'No usable pictures' };
      }
      if (assignment.leftOut > 0) reasons.push(`Only ${ordered.length} usable picture(s): ${assignment.leftOut} body image(s) left out.`);

      const K = titleCaseKeyword(ctx.task.keyword);
      const slug = slugFor(ctx);
      const vars = { title: ctx.task.selectedTitle ?? '', keyword: K, image_text: K };

      const fSlots = slotSizes(featuredDesign);
      const fPics: RenderPicture[] = [];
      for (let i = 0; i < assignment.featured.length; i++) fPics.push(await preparePicture(ctx, assignment.featured[i]!, fSlots[i + 1] ?? { w: 1920, h: 1080 }, notes));
      const featuredOut = taskMedia(ctx.task.id, `${slug}.webp`);
      await fs.writeFile(featuredOut.abs, await toWebp(await renderDesign(featuredDesign, { pictures: fPics, logo, vars }), 90));

      const body: ImagesData['body'] = [];
      const bodyDesign = designFor('body', website, accent, 1);
      const bSlot = slotSizes(bodyDesign)[1] ?? { w: 1920, h: 1080 };
      for (let i = 0; i < assignment.body.length; i++) {
        const p = assignment.body[i]!;
        const pic = await preparePicture(ctx, p, bSlot, notes);
        const out = taskMedia(ctx.task.id, `${slug}-${i + 1}.webp`);
        await fs.writeFile(out.abs, await toWebp(await renderDesign(bodyDesign, { pictures: [pic], logo, vars }), 90));
        body.push({ key: `body-${i + 1}`, path: out.rel, alt: altText(K, p.alt) });
      }
      const data: CelebImagesData = {
        featured: { path: featuredOut.rel, alt: altText(K, assignment.featured[0]!.alt) },
        body,
        pictures: ordered,
        photoChecked: checked,
        notes: notes.filter((n) => n !== 'upscayl-missing'),
      };
      await writeLog({ taskId: ctx.task.id, category: 'SYSTEM', stage: 'IMAGES', message: `Images ready: featured (${assignment.featured.length} picture(s)) and ${body.length} body image(s) from ${ordered.length} picture(s).`, data: { notes: data.notes } });
      return { outcome: 'completed', data, reviewReasons: reasons, message: `Featured image and ${body.length} body image(s)` };
    },
  };
}
